-- Align Supabase tables with the application persistence layer.
-- Main goals:
-- 1. campaign_results uses campaign_id + uuid only; campaign_uuid is migrated away.
-- 2. shortages stores every field returned by CampaignShortageRecord, plus raw_payload.

