do $$
declare
  classes_udt text;
begin
  select udt_name
  into classes_udt
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'shortages'
    and column_name = 'unavailable_classes';

  if classes_udt is not null and classes_udt <> '_text' then
    execute $sql$
      alter table public.shortages
      alter column unavailable_classes type text[]
      using case
        when unavailable_classes is null then '{}'::text[]
        when btrim(unavailable_classes::text) = '' then '{}'::text[]
        when left(btrim(unavailable_classes::text), 1) = '{' then unavailable_classes::text[]
        else string_to_array(unavailable_classes::text, ',')
      end
    $sql$;
  end if;
end $$;

update public.shortages
set
  uuid = coalesce(nullif(uuid, ''), gen_random_uuid()::text),
  source_record_id = coalesce(nullif(source_record_id, ''), id::text),
  time_slot = coalesce(nullif(time_slot, ''), nullif(prices->>'timeSlot', '')),
  arrondissement_origin = coalesce(nullif(arrondissement_origin, ''), nullif(prices->>'arrondissementOrigin', '')),
  arrondissement_dest = coalesce(nullif(arrondissement_dest, ''), nullif(prices->>'arrondissementDest', '')),
  jams = coalesce(
    jams,
    case
      when lower(coalesce(prices->>'jams', '')) in ('true', 'false') then (prices->>'jams')::boolean
      else false
    end
  ),
  price_yango_eco = coalesce(price_yango_eco, nullif(prices #>> '{yango,eco}', '')::numeric),
  price_hero_eco = coalesce(price_hero_eco, nullif(prices #>> '{heroCab,eco}', '')::numeric),
  raw_payload = case
    when raw_payload = '{}'::jsonb then jsonb_build_object(
      'id', coalesce(source_record_id, id::text),
      'uuid', uuid,
      'campaignId', campaign_id,
      'cityName', city_name,
      'cityId', city_id,
      'origin', origin,
      'destination', destination,
      'startNeighborhoodId', start_neighborhood_id,
      'endNeighborhoodId', end_neighborhood_id,
      'arrondissementOrigin', arrondissement_origin,
      'arrondissementDest', arrondissement_dest,
      'timestamp', created_at,
      'timeSlot', time_slot,
      'distanceKm', distance_km,
      'durationMinutes', duration_minutes,
      'waitingMinutes', waiting_time_minutes,
      'unavailableClasses', unavailable_classes,
      'jams', jams,
      'priceYangoEco', price_yango_eco,
      'priceHeroEco', price_hero_eco
    )
    else raw_payload
  end;

update public.shortages
set raw_payload = jsonb_set(raw_payload, '{uuid}', to_jsonb(uuid), true)
where raw_payload->>'uuid' is null;

